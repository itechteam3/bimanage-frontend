// Generates src/styles/theme.css (Tailwind v4 @theme) from
// docs/figma/design-tokens.json. Run with `npm run tokens` (also runs before
// dev and build). Tailwind's default palette, radii, shadows and type scale
// are switched off, so only design tokens exist as utilities.
//
// Utility names:
//   colours   bg-brand-navy, text-ink-strong, bg-surface-pale, border-line-default,
//             text-success, bg-danger-bg …
//   type      text-body-sm, text-card-heading, text-page-title …  (size + line height + weight)
//   spacing   p-4 = 16px (4px base, matches the 4/8/12/16/24/32/40 scale);
//             named sizes h-control-lg, w-sidebar, h-header …
//   radius    rounded-sm (8) rounded-md (10) rounded-lg (12) rounded-xl (16) rounded-2xl (20) rounded-3xl (22)
//   shadow    shadow-card, shadow-floating, shadow-focus …
//   gradients bg-gradient-brand-panel, bg-gradient-atmosphere
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = resolve(root, "docs/figma/design-tokens.json");
const OUT = resolve(root, "src/styles/theme.css");

export function buildThemeCss(tokens) {
  const rem = (px) => `${+(px / 16).toFixed(4)}rem`;
  const val = (t) => t.$value;
  const lines = [];
  const push = (name, value, note) => lines.push(`  --${name}: ${value};${note ? ` /* ${note} */` : ""}`);

  // Colours. Group prefixes keep utilities readable: text.* → ink-*, border.* → line-*,
  // status.* → flat (success, danger-bg …).
  const groupPrefix = { brand: "brand-", text: "ink-", surface: "surface-", border: "line-", status: "" };
  lines.push("  /* colour */", "  --color-*: initial;");
  for (const [group, entries] of Object.entries(tokens.color)) {
    if (group.startsWith("$")) continue;
    for (const [name, t] of Object.entries(entries)) {
      if (name.startsWith("$")) continue;
      push(`color-${groupPrefix[group] ?? `${group}-`}${name}`, val(t));
    }
  }

  // Type
  lines.push("", "  /* type */", "  --text-*: initial;");
  push("font-sans", val(tokens.font.family.sans).map((f) => (f.includes(" ") || f === "Poppins" ? `"${f}"` : f)).join(", "));
  for (const [name, t] of Object.entries(tokens.typography)) {
    if (name.startsWith("$")) continue;
    const v = val(t);
    push(`text-${name}`, rem(v.fontSize), `${v.fontSize}px`);
    push(`text-${name}--line-height`, `${+(v.lineHeight / v.fontSize).toFixed(4)}`, `${v.lineHeight}px`);
    push(`text-${name}--font-weight`, String(v.fontWeight));
  }

  // Spacing: 4px base; named component sizes.
  lines.push("", "  /* spacing & sizes */", "  --spacing: 0.25rem; /* 4px — p-1=4, p-2=8, p-3=12, p-4=16, p-6=24, p-8=32, p-10=40 */");
  for (const [name, t] of Object.entries(tokens.size)) {
    if (name.startsWith("$")) continue;
    push(`spacing-${name}`, val(t));
  }

  // Radius
  lines.push("", "  /* radius */", "  --radius-*: initial;");
  for (const [name, t] of Object.entries(tokens.radius)) {
    if (name.startsWith("$")) continue;
    push(`radius-${name}`, val(t));
  }

  // Shadows
  lines.push("", "  /* elevation */", "  --shadow-*: initial;");
  for (const [name, t] of Object.entries(tokens.shadow)) {
    if (name.startsWith("$")) continue;
    push(`shadow-${name}`, val(t));
  }

  // Breakpoints (mobile first)
  lines.push("", "  /* breakpoints */", "  --breakpoint-*: initial;");
  for (const [name, t] of Object.entries(tokens.breakpoint)) {
    if (name.startsWith("$") || name === "mobile") continue;
    push(`breakpoint-${name}`, val(t));
  }

  // Gradients and border widths are plain custom properties with utilities below.
  const extras = [];
  for (const [name, t] of Object.entries(tokens.gradient)) {
    if (name.startsWith("$")) continue;
    extras.push(`  --gradient-${name}: ${val(t)};`);
  }
  for (const [name, t] of Object.entries(tokens["border-width"])) {
    if (name.startsWith("$")) continue;
    extras.push(`  --border-width-${name}: ${val(t)};`);
  }

  const gradientUtilities = Object.keys(tokens.gradient)
    .filter((n) => !n.startsWith("$") && !n.startsWith("glow"))
    .map((n) => `@utility bg-gradient-${n} {\n  background-image: var(--gradient-${n});\n}`)
    .join("\n\n");

  return `/* GENERATED by scripts/build-tokens.mjs from docs/figma/design-tokens.json — do not edit. */

@theme {
${lines.join("\n")}
}

:root {
${extras.join("\n")}
}

${gradientUtilities}

@utility border-outlined {
  border-width: var(--border-width-outlined-button);
}
`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const tokens = JSON.parse(readFileSync(SRC, "utf8"));
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, buildThemeCss(tokens));
  console.log(`tokens → ${OUT.replace(root + "\\", "").replace(root + "/", "")}`);
}
